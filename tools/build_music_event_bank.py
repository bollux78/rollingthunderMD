#!/usr/bin/env python3
"""Convert normalized musical data to native event records, never CPU code."""
from pathlib import Path
import json
root=Path(__file__).resolve().parents[1]
def build():
 data=json.loads((root/'assets/extracted/logic/game_over_music_events.json').read_text())
 assert data['format']=='native-music-events-v1' and data['source_sha256']=='4ab04d23bc2fd1bd788122e39ad94451781e5b370387c64a1abf60f02ca940c3'
 names=dict(master_gain='GAIN',tempo_base='BASE',tempo_multiplier='MULTIPLIER',key_notes='NOTES',instruments='INSTRUMENTS',channel_gains='CHANNEL_GAINS',pitch_fraction='FRACTION',pitch_only='PITCH',channel_modulation='MODULATION',lfo_frequency='LFO',phase_modulation_depth='PHASE_DEPTH',amplitude_modulation_depth='AMPLITUDE_DEPTH',lfo_waveform='WAVEFORM',end='END')
 lines=['/* Generated by tools/build_music_event_bank.py. */','#include "rt_music_sequence.h"'];rows=[]
 for i,e in enumerate(data['events']):
  kind=names[e['event']];mask=0;pointer='0'
  if 'channels' in e:
   stride=28 if kind=='INSTRUMENTS' else 1;values=[0]*(8*stride)
   for channel in e['channels']:
    n=channel['channel'];mask|=1<<n
    values[n*stride:(n+1)*stride]=list(bytes.fromhex(channel['operator_data'])[:28]) if stride==28 else [channel['value']]
   pointer=f'parameters{i}'
   lines.append('static const u8 '+pointer+'[]={'+','.join(map(str,values))+'};')
  rows.append('{'+f'{e.get("value",0)},RT_MUSIC_EVENT_{kind},{mask},{pointer}'+'}')
 lines+=['static const RT_MusicEvent events[]={'+',\n'.join(rows)+'};','static const u16 tracks[]={'+','.join(['65535']*12+['0'])+'};','const RT_MusicEventBank rtGameOverMusicBank={events,tracks,sizeof(events)/sizeof(events[0]),13};','']
 return '\n'.join(lines)

def build_all(selectors=None,bank_name=None):
 if bank_name is None:bank_name='rtGameOverChainMusicBank' if selectors is not None else 'rtArcadeMusicBank'
 if not bank_name.isidentifier():raise ValueError('Invalid C bank name')
 graph=json.loads((root/'assets/extracted/logic/music_graph.json').read_text())
 if selectors is not None:
  tracks={t['selector']:t['address'] for t in graph['tracks']}
  by_address={e['address']:e for e in graph['events']}
  needed=set();selected=set(selectors);pending=[tracks[n] for n in selectors]
  while pending:
   address=pending.pop()
   if address in needed:continue
   needed.add(address);event=by_address[address]
   for edge in ('next','return','target','subsequent_target'):
    if edge in event:pending.append(event[edge])
   if event['event'] in ('call','track'):
    selected.add(event['track']);pending.append(tracks[event['track']])
  graph['events']=[e for e in graph['events'] if e['address'] in needed]
  graph['tracks']=[t for t in graph['tracks'] if t['selector'] in selected]
 events=graph['events'];indices={e['address']:i for i,e in enumerate(events)}
 names=dict(master_gain='GAIN',tempo_base='BASE',tempo_multiplier='MULTIPLIER',key_notes='NOTES',instruments='INSTRUMENTS',channel_gains='CHANNEL_GAINS',pitch_fraction='FRACTION',pitch_only='PITCH',channel_modulation='MODULATION',lfo_frequency='LFO',phase_modulation_depth='PHASE_DEPTH',amplitude_modulation_depth='AMPLITUDE_DEPTH',lfo_waveform='WAVEFORM',end='END',call='CALL',track='TRACK',jump='JUMP',yield_='YIELD',repeat='REPEAT',conditional='CONDITIONAL')
 lines=['/* Generated by tools/build_music_event_bank.py from verified source data. */','#include "rt_music_sequence.h"'];rows=[];payloads={}
 for i,e in enumerate(events):
  kind=names['yield_' if e['event']=='yield' else e['event']];mask=0;values=None;value=e.get('value',0)
  if 'channels' in e:
   stride=28 if kind=='INSTRUMENTS' else 1;values=[0]*(8*stride)
   for c in e['channels']:
    ch=c['channel'];mask|=1<<ch
    values[ch*stride:(ch+1)*stride]=list(bytes.fromhex(c['operator_data'])[:28]) if stride==28 else [c['value']]
  if kind in ('CALL','TRACK'):value=e['track']
  if kind=='JUMP':value=indices[e['target']]
  if kind in ('REPEAT','CONDITIONAL'):
   value=e['count'];first=indices[e['target']];repeat=indices.get(e.get('subsequent_target'),65535)
   values=[first>>8,first&255,repeat>>8,repeat&255]
  if 'next' in e:assert indices[e['next']]==i+1
  if 'return' in e:assert indices[e['return']]==i+1
  pointer='0'
  if values is not None:
   key=tuple(values)
   if key not in payloads:
    payloads[key]=f'parameters{len(payloads)}';lines.append('static const u8 '+payloads[key]+'[]={'+','.join(map(str,values))+'};')
   pointer=payloads[key]
  rows.append('{'+f'{value},RT_MUSIC_EVENT_{kind},{mask},{pointer}'+'}')
 tracks=[65535]*(max(t['selector'] for t in graph['tracks'])+1)
 for t in graph['tracks']:tracks[t['selector']]=indices[t['address']]
 lines+=['static const RT_MusicEvent events[]={'+',\n'.join(rows)+'};','static const u16 tracks[]={'+','.join(map(str,tracks))+'};',f'const RT_MusicEventBank {bank_name}={{events,tracks,{len(rows)},{len(tracks)}}};','']
 return '\n'.join(lines)

if __name__=='__main__':
 (root/'src/music_event_bank.c').write_text(build())
 (root/'src/arcade_music_bank.c').write_text(build_all())
 (root/'src/game_over_chain_music_bank.c').write_text(build_all((11,12)))
 (root/'src/final_music_bank.c').write_text(build_all((7,9,11),'rtFinalMusicBank'))
