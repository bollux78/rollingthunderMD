#!/usr/bin/env python3
"""Packs the 62 extracted 63701X sample clips (assets/extracted/voices_6khz,
unsigned 8-bit, 6000 Hz) for the Z80 music/sample driver.

Clips are resampled (linear) to the driver's DAC clock: YM2612 Timer A with
NA=1014 -> 7670453 / (144 * 10) = 5326.7 Hz, so pitch matches the arcade.

Output C array rtVoiceZ80Blob (32 KB aligned, boot-safe .rodata_binf in ROM
window 1). Layout, little-endian, offsets relative to blob start:
  64 entries x 5 bytes: offset (3 bytes), length (2 bytes); index = bank2*32 + sample
  (bank 0 -> 0..31, bank 2 -> 32..63, sample 0 unused); length 0 = none
  then the sample bytes.
Usage: build_voice_z80_blob.py VOICE_DIR OUT_C"""
import json, sys, wave, os

DAC_RATE = 7670453 / (144 * 10)
src_dir, out_c = sys.argv[1:3]
manifest = json.load(open(os.path.join(src_dir, 'manifest.json')))
entries = [(0, 0)] * 64
data = bytearray()
header = 64 * 5
for item in manifest:
    bank, sample = item['bank'], item['sample']
    w = wave.open(os.path.join(src_dir, 'bank%d_sample%02d.wav' % (bank, sample)))
    assert w.getframerate() == 6000 and w.getsampwidth() == 1 and w.getnchannels() == 1
    pcm = w.readframes(w.getnframes())
    n = int(len(pcm) * DAC_RATE / 6000)
    out = bytearray()
    for i in range(n):
        t = i * 6000 / DAC_RATE
        k = int(t); f = t - k
        a = pcm[k]; b = pcm[k + 1] if k + 1 < len(pcm) else 128
        out.append(max(0, min(255, round(a + (b - a) * f))))
    assert len(out) < 65536
    entries[(32 if bank == 2 else 0) + sample] = (header + len(data), len(out))
    data += out
blob = bytearray()
for off, length in entries:
    blob += off.to_bytes(3, 'little') + length.to_bytes(2, 'little')
blob += data
with open(out_c, 'w') as f:
    f.write('/* Generated by tools/audio/build_voice_z80_blob.py -- do not edit. */\n#include <genesis.h>\n')
    f.write('/* 63701X sample clips for the Z80 driver at %.2f Hz, in ROM window 1. */\n' % DAC_RATE)
    f.write('const u8 rtVoiceZ80Blob[%d] __attribute__((aligned(32768),section(".rodata_binf")))={\n' % len(blob))
    for i in range(0, len(blob), 32):
        f.write(','.join(str(b) for b in blob[i:i + 32]) + (',\n' if i + 32 < len(blob) else '\n'))
    f.write('};\n')
print('voice blob', len(blob), 'bytes,', len(manifest), 'clips')
